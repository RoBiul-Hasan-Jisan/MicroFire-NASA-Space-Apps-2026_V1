import { writeFileSync } from 'node:fs';
import { answerQuestion, catalog, correctTerm, indexExperiment, rankStatements } from '@microfire/science';

/**
 * Evaluates the classical-ML/IR additions. Labels are author-written, the corpus is one record, so these are regression
 * checks, not statistical estimates. Deterministic: no network, no model.
 */
const vocab = new Set<string>();
for (const e of catalog.experiments) { const i = indexExperiment(e); i.vocab.forEach((t) => vocab.add(t)); i.fieldTokens.forEach((_, t) => vocab.add(t)); }

// 1. Typo robustness: does a misspelled question release the same statements as the clean one?
const pairs: [string, string][] = [
  ['What oxygen concentration was recorded for B20?', 'What oxigen concentration was recorded for B20?'],
  ['How thick was the B20 PMMA film?', 'How thicknes was the B20 PMMA film?'],
  ['What was the pressure during B20?', 'What was the presure during B20?'],
  ['What flow direction was used in B20?', 'What flow directoin was used in B20?'],
  ['What was the film thickness in B20?', 'What was the film thikness in B20?'],
  ['What oxygen concentration was recorded for B20?', 'What oxgyen concentration was recorded for B20?']
];
const ask = (q: string) => answerQuestion({ question: q, targetConditions: {} });
const same = (a: string, b: string) => { const x = ask(a), y = ask(b); return !x.abstained && !y.abstained && JSON.stringify(x.statements) === JSON.stringify(y.statements); };
const cleanOk = pairs.filter(([c]) => !ask(c).abstained).length;
const typoRecovered = pairs.filter(([c, t]) => same(c, t)).length;
const rows = pairs.map(([c, t]) => `| ${t} | ${same(c, t) ? 'PASS' : 'FAIL'} |`);

// 2. False corrections: ordinary non-typo words must never be rewritten.
const legit = ['cotton', 'titanium', 'kerosene', 'heater', 'paper', 'orbit', 'station', 'candle', 'carbon', 'helium', 'nitrogen', 'astronaut', 'spacecraft', 'laminar', 'turbulent', 'diffusion', 'radiation', 'ignition', 'extinction', 'polymer', 'cellulose', 'sooting', 'video', 'camera', 'sensor', 'chamber', 'module', 'cabin'];
const falseFixes = legit.filter((w) => correctTerm(w, vocab) !== null);

// 3. BM25 statement ranking, MRR@3 against the statement a reader would want.
const cases: [string, string][] = [
  ['oxygen concentration', 'condition:oxygenPct'], ['what pressure', 'condition:pressureKpa'], ['film thickness', 'condition:thicknessMm'],
  ['flame burned the sample', 'claim:'], ['microgravity acceleration level', 'condition:gravity'], ['flow direction', 'condition:flowDirection']
];
let mrr = 0;
const bmRows = cases.map(([q, want]) => {
  const hits = rankStatements(q, 3); const rank = hits.findIndex((h) => h.doc.id.includes(want)) + 1;
  mrr += rank ? 1 / rank : 0;
  return `| ${q} | ${want} | ${rank || 'not in top 3'} |`;
});
mrr /= cases.length;

const report = `# ML evaluation report (generated)

Generated by \`npm run eval:ml\`. Do not edit by hand. Classical, deterministic, offline techniques only (no language model, no network).
Labels are author-written and the corpus is one validated record, so these are **regression checks, not statistical estimates**.

## Summary

| Metric | Result |
|---|---|
| Clean questions answered | ${cleanOk}/${pairs.length} |
| Misspelled questions that release exactly the same cited statements as the clean question | ${typoRecovered}/${pairs.length} |
| Ordinary non-typo words wrongly rewritten | ${falseFixes.length}/${legit.length}${falseFixes.length ? ` (${falseFixes.join(', ')})` : ''} |
| BM25 statement ranking, MRR@3 | ${mrr.toFixed(3)} over ${cases.length} queries |

## Typo robustness

| Misspelled question | Same statements as clean question |
|---|---|
${rows.join('\n')}

## BM25 statement ranking

| Query | Expected statement | Rank |
|---|---|---|
${bmRows.join('\n')}

## Known ceilings

- The vocabulary comes from a single record, so few correctable terms exist. Re-run this evaluation whenever the catalog grows.
- Inflected typos only recover when the catalog holds a close stem; e.g. "obsreved" is not corrected because the catalog only contains "observation". This is deliberate: thresholds are not loosened to chase such cases.
- Ambiguous corrections (two equally close terms) are deliberately not applied.
- BM25 here is exported and measured but not used to release answers; Ask PIX still answers only from cited catalog statements.
`;
writeFileSync('docs/evals/ml-report.md', report);
console.log(`typo recovered ${typoRecovered}/${pairs.length}, false fixes ${falseFixes.length}/${legit.length}, BM25 MRR@3 ${mrr.toFixed(3)}. Wrote docs/evals/ml-report.md`);
if (typoRecovered !== pairs.length || falseFixes.length || mrr < 0.8) process.exitCode = 1;
